3. 密码、验证码、支付、转账、银行、证券、基金、钱包、贷款、身份证、实名、指纹、面容、解锁、登录注册等界面，整屏跳过，连界面名字都不记。
4. 不截图、不录屏、不读剪贴板、不读相册、不读通知内容、不读取通讯录或任何聊天正文。

三、她会学到什么，能做什么（重要，请读完）
1. 她会从你反复做的操作里，总结出「一条路径」——比如在某个应用里连续点 A、B、C。这样的路径会成为一条「候选动作」，默认状态是什么都不会做，只等你来看。
2. 只有你在设置里逐条点「收下」，它才会变成她可以执行的动作。没有你的点击，任何一条候选都不会被执行，也不会被写进她跟你聊天时看的上下文。
3. 即使她收下了，每次真要做之前还会再问你一次，说清打算点哪几步，你点头才动手。
4. 她执行时**只按按钮上的文字去找按钮**，不记忆、也不使用屏幕坐标。找不到那个按钮，她就停下并告诉你停在哪一步，不会随手乱点。
5. 涉及支付、付款、转账、红包、充值、提现、购买、下单、结算、卸载、注销、解绑、删除账号、退出登录的路径，永远不会被学成可执行动作——这类路径连候选都不会出现。
6. 会改动内容的动作（发送、发布、删除、评论、关注等）即使被学会，也会被标红提示，执行前需要你确认。
7. 她的路径是从你自己的操作里归纳的，因此可能包含你本人的偏好与判断。是否让她替你操作，完全由你决定。

四、数据存在哪里
只存在这台手机上，应用自己的私有目录里，其他应用无权读取。原始记录最多保留 7 天，之后自动删除；只留下「你常用哪些应用、大致什么时段」这样的统计结论，以及你确认过的动作路径。

五、有一件事你必须知道
统计结论（以及你收下的动作路径）会作为提示词的一部分，在你和她对话时一并发给你自己配置的大模型服务商（例如 DeepSeek、通义千问）。也就是说：这些内容会离开这台手机，进入你所选定的服务商。除此之外，本功能不会向任何第三方上传任何数据。

六、你随时可以反悔
在设置里关掉开关，采集立刻停止，已经学会的动作也一并停用（她既不会提，也不会执行）。点「清除学习数据」，已采集的原始记录、统计结论和你确认过的动作路径会被全部删除，不可恢复。撤回同意等同于关闭。

七、风险提示
1. 本功能依赖系统无障碍服务。部分系统（如 vivo / iQOO）可能因此判定为高风险应用并限制后台，耗电会略有增加。
2. 无障碍服务本身权限很高。请确认你信任本应用后再开启。
3. 统计结论可能有偏差，仅供参考，不构成任何建议，也不应作为任何决策依据。
4. 即使有上述限制，自动操作仍有可能因为界面变化而点错位置。请在让她执行时留意屏幕，随时可以让她停下。
5. 你在使用本功能过程中自行承担相应风险。因使用本功能产生的任何后果，由使用者自行承担。

八、确认
点击「我已阅读并同意」表示：你已理解上述采集范围、数据流向，以及「她可能代你执行操作」这件事，并自愿开启该功能。
