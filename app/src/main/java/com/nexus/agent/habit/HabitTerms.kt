【自我学习 · 功能说明与免责声明】

请先读完再决定是否开启。这不是必选项，不开启完全不影响其他任何功能。
（每次开启前需要停留阅读 20 秒，倒计时结束才能点同意。）

一、这个功能做什么
开启后，宏月在系统无障碍服务的协助下，留意你「怎么操作手机」：打开了哪些应用、进的是哪个界面、点了哪个按钮、大概几点做的。她据此总结你的使用习惯，让平时聊天更像一个熟悉你的人，而不是每次都要问「你在忙什么」。

二、她绝不会采集什么
1. 任何输入框里的内容。你打的每个字——聊天、搜索、地址、备注——一律不采集。输入框在她眼里只等于三个字：「输入框」。
